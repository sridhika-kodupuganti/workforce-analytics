/**
 * Filter employees based on active dashboard filters
 */
export function filterEmployees(
  employees: Employee[],
  filters: DashboardFilters,
): Employee[] {
  return employees.filter((emp) => {
    // Department filter
    if (filters.department !== 'All' && emp.department !== filters.department) {
      return false;
    }
    // Location filter
    if (filters.location !== 'All' && emp.location !== filters.location) {
      return false;
    }
    // Status filter
    if (filters.status !== 'All' && emp.status !== filters.status) {
      return false;
    }
    // Search query
    if (filters.searchQuery.trim() !== '') {
      const q = filters.searchQuery.toLowerCase();
      const matchName = emp.name.toLowerCase().includes(q);
      const matchEmail = emp.email.toLowerCase().includes(q);
      const matchRole = emp.role.toLowerCase().includes(q);
      const matchDept = emp.department.toLowerCase().includes(q);
      const matchLoc = emp.location.toLowerCase().includes(q);
      if (!matchName && !matchEmail && !matchRole && !matchDept && !matchLoc) {
        return false;
      }
    }
    return true;
  });
}

/**
 * Filter activities based on active filters
 */
export function filterActivities(
  activities: ActivityItem[],
  filters: DashboardFilters,
): ActivityItem[] {
  return activities.filter((act) => {
    if (filters.department !== 'All' && act.department !== filters.department) {
      return false;
    }
    if (filters.searchQuery.trim() !== '') {
      const q = filters.searchQuery.toLowerCase();
      const matchName = act.employeeName.toLowerCase().includes(q);
      const matchType = act.activityType.toLowerCase().includes(q);
      const matchDetails = act.details.toLowerCase().includes(q);
      if (!matchName && !matchType && !matchDetails) {
        return false;
      }
    }
    return true;
  });
}
